#!/usr/bin/env python3
"""
nginx 配置生成器 (master 分支合并版)

数据:
  gen/domains.json — 主域名(证书组): 每组共享一张通配符证书
  gen/sites.json   — 功能表, 两种模式:
      A. 矩阵模式: "prefixes": ["x", ...] → 每个证书组展开 "前缀.域名"
      B. 显式模式: "server_names": {"<组名>": ["a.810114.xyz", "*.nmbyd2.top", ...]}
         (通配符 server_name 用显式模式)

生成:
  sites-enabled/site-<name>.conf — 每个证书组一个 server 块 (SSL 隔离)

用法:
  python3 gen/gen.py [--out sites-enabled] [--dry-run]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SERVER_HEADER = """# AUTO-GENERATED by gen/gen.py — DO NOT EDIT MANUALLY.
# 数据源: gen/domains.json + gen/sites.json
"""


def load_json(path: Path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def render_server_block(server_names, ssl_conf, route, extra_snippets=None):
    sn = " ".join(server_names)
    lines = [
        "server {",
        "    listen 443 ssl http2;",
        "    listen [::]:443 ssl http2;",
        f"    server_name {sn};",
        f"    include {ssl_conf};",
        "    include /etc/nginx/snippets/doh.conf;",
        "    include /etc/nginx/snippets/v2ray.conf;",
    ]
    if route:
        lines.append(f"    include {route};")
    for s in (extra_snippets or []):
        lines.append(f"    include {s};")
    lines += [
        "    access_log off;",
        "    error_log /dev/null;",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="sites-enabled")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    domains = load_json(ROOT / "gen" / "domains.json")
    sites = load_json(ROOT / "gen" / "sites.json")
    groups = {g["name"]: g for g in domains["cert_groups"]}
    out_dir = ROOT / args.out

    generated = []
    for site in sites["sites"]:
        name = site["name"]
        route = site.get("route")
        extra = site.get("extra_snippets") or []

        blocks = []
        if "server_names" in site:
            # 显式模式: {"组名": [server_name...]}
            for gname, names in site["server_names"].items():
                group = groups[gname]
                blocks.append(render_server_block(names, group["ssl"], route, extra))
        else:
            # 矩阵模式: prefixes × 证书组
            prefixes = site["prefixes"]
            for group in domains["cert_groups"]:
                server_names = [f"{p}.{d}" for p in prefixes for d in group["domains"]]
                if server_names:
                    blocks.append(render_server_block(server_names, group["ssl"], route, extra))

        if not blocks:
            print(f"[skip] {name}: no blocks")
            continue

        content = SERVER_HEADER + "\n" + "\n".join(blocks)
        out_file = out_dir / f"site-{name}.conf"
        generated.append(out_file.name)
        if args.dry_run:
            print(f"[dry-run] {out_file.relative_to(ROOT)}")
        else:
            out_file.write_text(content, encoding="utf-8")
            print(f"[write] {out_file.relative_to(ROOT)}")

    print(f"\n== generated {len(generated)} files ==")
    for g in sorted(generated):
        print("  ", g)


if __name__ == "__main__":
    main()
